fn main() -> Result<(), Box<dyn std::error::Error>> {
    tonic_build::configure()
        .build_server(true)
        .build_client(true)
        .boxed(".wuphf.connector.v1.ServerFrame.body.message_create")
        .compile_protos(
            &[
                "common.proto",
                "media.proto",
                "client.proto",
                "server.proto",
                "connector.proto",
                "observer.proto",
                "functions.proto",
                "plugin.proto",
                "health.proto",
            ],
            &["."],
        )?;
    Ok(())
}
